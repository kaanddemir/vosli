const num = (value: number) => formatCountIn('en', value);
const list = (values: readonly number[]) => values.map(num).join(', ');
const plurals = new Intl.PluralRules('en-US');
const isOne = (value: number) => plurals.select(value) === 'one';
/** 1 word, 2 words, 1,284 words. */
